#!/usr/bin/env python3
"""Build the essay pages: writing/<slug>.html, and their cards on the landing.

Each page = the shared shell (head, icon sprite, sidebar, footer, lifted from
index.html by scripts/build-case-studies.py's helpers) + an article from
content/writing/<slug>.html, described by content/writing/essays.json. The
article fragments are written elsewhere (the Simonides repo renders its essay
with scripts/essay_html.py) and committed here. The cards between the
ESSAYS markers in index.html are regenerated from the same manifest.

    python3 scripts/build-writing.py

Run it after scripts/build-case-studies.py (the shell comes from index.html),
then commit writing/*.html. Stdlib only.
"""
import html
import importlib.util
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content" / "writing"
OUT = ROOT / "writing"
SITE = "https://nikolasneofytou.com"

spec = importlib.util.spec_from_file_location("cs", ROOT / "scripts" / "build-case-studies.py")
cs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cs)


def write_cards(essays: list) -> None:
    """Regenerate the essay cards between the ESSAYS markers in index.html."""
    path = ROOT / "index.html"
    text = path.read_text()
    start = text.index("\n", text.index("<!-- ESSAYS:START")) + 1
    end = text.index("                <!-- ESSAYS:END -->")
    cards = []
    for e in essays:
        d = e["date"]
        when = f"{int(d[8:10])} {['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'][int(d[5:7]) - 1]} {d[:4]}"
        cards.append(f"""                    <a class="writing-card" href="writing/{e['slug']}.html">
                        <div class="writing-date">{when} · {e['reading_minutes']} min read</div>
                        <h3 class="writing-title">{html.escape(e['title'])}</h3>
                        <p class="writing-excerpt">{html.escape(e['excerpt'])}</p>
                    </a>""")
    block = '                <div class="writing-list writing-list--here">\n' + "\n".join(cards) + "\n                </div>\n"
    path.write_text(text[:start] + block + text[end:])
    print(f"index.html: {len(essays)} essay card(s)")


def main() -> None:
    essays = [e for e in json.loads((CONTENT / "essays.json").read_text()) if not e.get("hidden")]
    write_cards(essays)
    index = (ROOT / "index.html").read_text()
    version = re.search(r'css/styles\.css\?v=([\w-]+)', index).group(1)
    sprite = cs.between(index, "    <!-- Icon sprite", "</svg>\n")
    sidebar = cs.relink(cs.between(index, '<header class="sidebar"', "</header>"))
    sidebar = sidebar.replace('href="../index.html#beyond" class="nav-link"',
                              'href="../index.html#beyond" class="nav-link active" aria-current="page"')
    footer = cs.between(index, '<footer class="site-footer">', "</footer>")
    OUT.mkdir(exist_ok=True)
    for e in essays:
        body = (CONTENT / f"{e['slug']}.html").read_text().rstrip()
        esc = {k: html.escape(str(v), quote=True) for k, v in e.items() if isinstance(v, str)}
        meta = "\n".join(f'                        <div><dt>{html.escape(k)}</dt><dd>{html.escape(v)}</dd></div>'
                         for k, v in e["meta"].items())
        url = f"{SITE}/writing/{e['slug']}.html"
        og_image = f"{SITE}/{e['og_image']}"
        subject = cs.mailto("About the essay: " + e["title"])
        # a painted cover, when the essay has one (same recipe and sizes as the case studies)
        has_cover = (ROOT / "assets" / "covers" / f"{e['slug']}-1344.webp").exists()
        preload = (f'\n    <link rel="preload" href="../assets/covers/{e["slug"]}-1344.webp" as="image" fetchpriority="high">'
                   if has_cover else "")
        hero = (f"""
                <figure class="cs-hero">
                    <img src="../assets/covers/{e['slug']}-1344.webp" width="1344" height="752" alt="{esc['og_alt']}"
                         fetchpriority="high" decoding="async">
                </figure>
""" if has_cover else "")
        page = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <!-- Generated by scripts/build-writing.py from content/writing/ — edit there, not here. -->
    <title>{esc['title']} · Nikolas Neofytou</title>
    <meta name="description" content="{esc['description']}">
    <meta name="author" content="Nikolas Neofytou">
    <meta name="theme-color" content="#F5F4EF">
    <link rel="canonical" href="{url}">
    <meta property="og:title" content="{esc['title']}">
    <meta property="og:description" content="{esc['description']}">
    <meta property="og:type" content="article">
    <meta property="article:published_time" content="{esc['date']}">
    <meta property="article:author" content="Nikolas Neofytou">
    <meta property="og:url" content="{url}">
    <meta property="og:site_name" content="Nikolas Neofytou">
    <meta property="og:image" content="{og_image}">
    <meta property="og:image:alt" content="{esc['og_alt']}">
    <meta name="twitter:card" content="summary_large_image">
    <link rel="icon" type="image/svg+xml" href="../assets/favicon.svg">
    <link rel="stylesheet" href="../css/styles.css?v={version}">
    <link rel="preload" href="../assets/fonts/instrument-serif.woff2" as="font" type="font/woff2" crossorigin>
    <link rel="preload" href="../assets/fonts/inter-var.woff2" as="font" type="font/woff2" crossorigin>{preload}
</head>
<body class="cs-page essay-page">
{sprite}
    <a class="skip-link" href="#content">Skip to content</a>

    <div class="layout">
        {sidebar}

        <main class="main" id="top">
            <article class="cs essay" id="content">
                <a class="cs-crumb" href="../index.html#beyond"><svg class="icon" aria-hidden="true" focusable="false"><use href="#i-chevron-left"></use></svg> Writing</a>

                <header class="cs-head">
                    <p class="cs-kicker"><span class="section-num">{esc['date'][:4]}</span> {esc['kicker']}</p>
                    <h1 class="cs-title essay-title">{esc['title']}</h1>
                    <p class="cs-lede">{esc['lede']}</p>
                    <dl class="cs-meta">
{meta}
                    </dl>
                </header>
{hero}
{body}
            </article>

            <aside class="cs-cta" aria-labelledby="essay-cta-h">
                <h2 class="cs-cta-h" id="essay-cta-h">Something to add, or something wrong?</h2>
                <p class="cs-cta-line">The essay comes out of a research project with graded sources and a pre-registered test; I would rather hear where it fails than where it pleases.</p>
                <div class="contact-ctas">
                    <a class="contact-cta" href="{subject}">{cs.ICON.format('envelope')} Write to me about this essay</a>
                    <button class="copy-btn" type="button" data-copy="{cs.EMAIL}" hidden>Copy email address</button>
                </div>
            </aside>

            <nav class="cs-next" aria-label="More writing">
                <a href="https://nikolasneofytou.substack.com" class="cs-next-link" target="_blank" rel="noopener noreferrer">
                    <span class="cs-next-label">More writing <svg class="icon" aria-hidden="true" focusable="false"><use href="#i-arrow-right"></use></svg></span>
                    <span class="cs-next-title">On Substack</span>
                    <span class="cs-next-lede">Philosophy and history: Camus, Marius, Schopenhauer, Columbia.</span>
                </a>
            </nav>

            {footer}
        </main>
    </div>

    <button class="back-to-top" id="backToTop" aria-label="Back to top"><svg class="icon" aria-hidden="true" focusable="false"><use href="#i-arrow-up"></use></svg></button>
    <script src="../js/script.js?v={version}"></script>
</body>
</html>
"""
        (OUT / f"{e['slug']}.html").write_text(page)
        print(f"writing/{e['slug']}.html")


if __name__ == "__main__":
    main()
